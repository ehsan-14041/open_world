#!/usr/bin/env python3
"""
H1 falsification test: does a real port queue behave like a stock?

    python scripts/test_queue_mechanism.py
    python scripts/test_queue_mechanism.py --write-report

Runs entirely on independently sourced observations. **No simulation is involved** — the
Event Simulator is not imported, no world is run, and no coefficient is touched. The point
is to find out whether a structural hypothesis is consistent with how the real system
behaves, before spending a held-out event on it.
"""

from __future__ import annotations

