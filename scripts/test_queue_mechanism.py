def render_h2_console(result: dict) -> str:
    out: list[str] = []
    rule = lambda t: f"\n{t}\n{'-' * len(t)}"  # noqa: E731
    h, p = result["hysteresis"], result["persistence"]

    out.append(f"H2 MECHANISM TEST — {result['title']}")
    out.append(f"series={result['series']}  n={result['n_months']} months  (no simulation involved)")
    out.append(f"\nPrediction stated before testing: {result['prediction_stated_before_testing']}")

    out.append(rule("CIRCULARITY GUARD"))
    out.append(f"  {result['circularity_warning']}")

    out.append(rule("HYSTERESIS — the decisive test (detrended, one cycle)"))
    cycle = h["cycle"]
    out.append(f"  cycle: {cycle['pressure_trough']} ({cycle['pressure_trough_value']:.1f}%) "
               f"-> {cycle['pressure_peak']} ({cycle['pressure_peak_value']:.1f}%)")
    out.append(f"  secular trend removed: {h['cover_trend_per_month']:+.5f} months of cover per month")
    for row in h["bins"]:
        if row.get("gap") is None:
            out.append(f"  CU {row['bin'][0]}-{row['bin'][1]}%: {row['note']}")
            continue
        out.append(
            f"  CU {row['bin'][0]}-{row['bin'][1]}%  up {row['up_mean_detrended_cover']:+.4f} "
            f"(n={row['n_up']})   down {row['down_mean_detrended_cover']:+.4f} (n={row['n_down']})"
            f"   gap {row['gap']:+.4f}   supports H2: {row['supports_h2']}"
        )
    out.append(f"  mean gap {h['mean_gap']:+.4f}  ->  supports H2: {h['supports_h2']}")

    out.append(rule("PERSISTENCE — the same question WITHOUT trend control"))
    if p.get("returned_to_baseline_pressure"):
        out.append(f"  pressure {p['baseline_pressure']:.1f}% ({p['baseline_month']}) "
                   f"-> {p['return_pressure']:.1f}% ({p['return_month']})")
        out.append(f"  cover {p['baseline_cover']:.3f} -> {p['cover_at_return']:.3f} "
                   f"(x{p['cover_ratio_vs_baseline']:.2f})   supports H2: {p['supports_h2']}")
        out.append("  NOTE: this comparison is NOT detrended. It disagrees with the")
        out.append("  hysteresis test above, and the difference IS the secular trend.")

    out.append(rule("VERDICT"))
    out.append(f"  {result['verdict']}")
    out.append(f"  {result['reason']}")

    out.append(rule("LIMITATIONS"))
    for item in result["limitations"]:
        out.append(f"  - {item}")
    out.append("")
    out.append(result["framing"])
    return "\n".join(out)


def render_h2_report(result: dict) -> str:
    lines: list[str] = []
    a = lines.append
    h, p = result["hysteresis"], result["persistence"]

    a("# H2 mechanism test — does a real order backlog behave like a stock?")
    a("")
    a("> Generated by `python scripts/test_queue_mechanism.py --h2 --write-report`. "
      "**No simulation is involved.** No coefficient was changed.")
    a("")
    a("## Why H2 needs a different test from H1")
    a("")
    a("[H1 was supported](H1_QUEUE_MECHANISM.md) by an increment-shape argument: that queue "
      "had a clean build phase under a flat driver, and relaxation is *structurally* barred "
      "from producing non-decaying increments under a steady driver.")
    a("")
    a("A backlog gives no such clean phase — its driver moves throughout, so shape alone is "
      "ambiguous. The distinctive signature of a stock is instead **path dependence**:")
    a("")
    a("| Form | Prediction |")
    a("|---|---|")
    a("| Relaxation | backlog is a function of CURRENT pressure — same pressure, same backlog |")
    a("| Stock (H2) | backlog is the INTEGRAL of past imbalances — same pressure, different backlog depending on the path |")
    a("")
    a(f"So the decisive test is hysteresis, and the prediction was stated before testing: "
      f"**{result['prediction_stated_before_testing']}**.")
    a("")

    a("## Two traps this test had to avoid")
    a("")
    a("**1. Circularity.**")
    a("")
    a(f"> {result['circularity_warning']}")
    a("")
    a("Verified empirically: the identity holds to about 1.1% median relative error, so New "
      "Orders is effectively a derived quantity. Federal Reserve capacity utilisation is used "
      "as the pressure variable instead — measured by a different agency, with no accounting "
      "relationship to unfilled orders.")
    a("")
    a("**2. Trend masquerading as hysteresis.** Backlog cover trends upward across the "
      "window, so an uncontrolled matched-pressure comparison across years measures the trend "
      "rather than path dependence. Cover is linearly detrended and the comparison restricted "
      "to a single capacity-utilisation cycle.")
    a("")

    a(f"## Data — {result['title']}")
    a("")
    a(result["definition"])
    a("")
    a("US Census M3 and Federal Reserve G.17 series, retrieved via FRED. **Public domain, so "
      "the series are stored in this repository** — the first fully redistributable data in "
      "the project.")
    a("")

    a("## Result 1 — hysteresis (detrended, within one cycle)")
    a("")
    cycle = h["cycle"]
    a(f"Cycle: pressure trough **{cycle['pressure_trough']}** "
      f"({cycle['pressure_trough_value']:.1f}%) → peak **{cycle['pressure_peak']}** "
      f"({cycle['pressure_peak_value']:.1f}%). Secular trend removed: "
      f"{h['cover_trend_per_month']:+.5f} months of cover per month.")
    a("")
    a("| Capacity utilisation | Up-leg (detrended cover) | Down-leg | Gap | Supports H2? |")
    a("|---|---|---|---|---|")
    for row in h["bins"]:
        if row.get("gap") is None:
            a(f"| {row['bin'][0]}–{row['bin'][1]}% | — | — | — | {row['note']} |")
            continue
        a(f"| {row['bin'][0]}–{row['bin'][1]}% | {row['up_mean_detrended_cover']:+.4f} "
          f"(n={row['n_up']}) | {row['down_mean_detrended_cover']:+.4f} (n={row['n_down']}) "
          f"| **{row['gap']:+.4f}** | {'yes' if row['supports_h2'] else '**no**'} |")
    a("")
    a(f"Mean gap **{h['mean_gap']:+.4f}** — the wrong sign. At matched capacity utilisation, "
      "backlog cover was *lower* on the way down than on the way up, which is the opposite of "
      "what a stock predicts.")
    a("")

    a("## Result 2 — the same question without trend control")
    a("")
    if p.get("returned_to_baseline_pressure"):
        a(f"Pressure returned to its starting level ({p['baseline_pressure']:.1f}% in "
          f"{p['baseline_month']} → {p['return_pressure']:.1f}% in {p['return_month']}), and "
          f"backlog cover over the same span went "
          f"**{p['baseline_cover']:.3f} → {p['cover_at_return']:.3f}** "
          f"(×{p['cover_ratio_vs_baseline']:.2f}).")
        a("")
        a("Taken at face value that is a **+28% persistent backlog** and looks like strong "
          "support for H2. It is not: this comparison is not detrended, and the entire gap is "
          "the secular trend that the controlled test removes.")
        a("")
        a("**The two tests disagree, and the disagreement is the finding.** The uncontrolled "
          "version would have promoted H2 on an artefact.")
    a("")

    a("## Verdict")
    a("")
    a(f"### {result['verdict']}")
    a("")
    a(f"{result['reason']}.")
    a("")

    a("## What this does and does not establish")
    a("")
    a("**Does establish:** in national aggregate manufacturing data, an order backlog does "
      "not show the path dependence a stock predicts, once the secular trend is removed.")
    a("")
    a("**Does not establish that H2 is wrong.** The test is *underpowered for the claim*: the "
      "model's `order_backlog` is a node-level, disruption-specific backlog, while this series "
      "aggregates every US manufacturing industry — averaging together sectors that are "
      "accumulating and sectors that are draining. That is precisely the kind of averaging "
      "that would hide a node-level stock.")
    a("")
    a(f"> {result['framing']}")
    a("")
    a("**H2 is therefore marked `not_supported`, not `rejected`, and is not deleted.**")
    a("")

    a("## A definitional problem this test exposed in the model")
    a("")
    a("`order_backlog` is currently described as *\"unfulfilled orders queued behind the "
      "disruption, including cargo waiting at anchor\"* — which conflates two different "
      "things with different dynamics and different observability:")
    a("")
    a("| Thing | Dynamics | Observability | Evidence |")
    a("|---|---|---|---|")
    a("| Cargo physically waiting at the port | integrates (H1) | proxy-observable | **supported** |")
    a("| Unfulfilled customer orders in the order book | not shown to integrate (H2) | latent at node level | **not supported** |")
    a("")
    a("One variable cannot carry both. Splitting them is a candidate structural change in its "
      "own right — and note it would be a change made for a *definitional* reason, not to "
      "improve a fit.")
    a("")

    a("## Limitations")
    a("")
    for item in result["limitations"]:
        a(f"- {item}")
    a("")

    a("## Consequence for the roadmap")
    a("")
    a("1. H1 — **independently supported**, may proceed to experimental implementation.")
    a("2. H2 — **not supported at this resolution**, does not proceed, is not deleted.")
    a("3. The topology sketch `queue_stock → delay → backlog_stock → inventory → service` is "
      "**half-supported**: the queue leg has independent evidence, the backlog leg does not. "
      "Building both at once would smuggle an untested mechanism in behind a tested one.")
    a("4. To test H2 properly, a node-level backlog series is needed — the same procurement "
      "problem as [event #3](EVENT3_SEARCH.md), and the same class of customer data that "
      "would ground the model's latent downstream half.")
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("series", nargs="?", default=None)
    parser.add_argument("--h2", action="store_true", help="run the H2 backlog test instead of H1")
    parser.add_argument("--write-report", action="store_true")
    parser.add_argument("--json", action="store_true")
    args = parser.parse_args()

    if args.h2:
        from event_sim.mechanism import compare_h2, load_backlog_series

        series = load_backlog_series(args.series or "us_manufacturing_backlog")
        result = compare_h2(series)
        print(json.dumps(result, indent=2, default=str) if args.json else render_h2_console(result))
        if args.write_report:
            REPORTS_DIR.mkdir(parents=True, exist_ok=True)
            path = REPORTS_DIR / "H2_BACKLOG_MECHANISM.md"
            path.write_text(render_h2_report(result) + "\n", encoding="utf-8")
            print(f"\nReport written to {path.relative_to(_PROJECT_ROOT)}")
        return 0

    bundle = load_queue_series(args.series or DEFAULT_SERIES)
    result = compare_candidates(bundle)

    if args.json:
        print(json.dumps(result, indent=2, default=str))
    else:
        print(render_console(result))

    if args.write_report:
        REPORTS_DIR.mkdir(parents=True, exist_ok=True)
        path = REPORTS_DIR / "H1_QUEUE_MECHANISM.md"
        path.write_text(render_report(result) + "\n", encoding="utf-8")
        print(f"\nReport written to {path.relative_to(_PROJECT_ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
