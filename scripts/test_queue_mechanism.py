import json
import sys
from pathlib import Path

_PROJECT_ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(_PROJECT_ROOT))

for _stream in (sys.stdout, sys.stderr):
    if hasattr(_stream, "reconfigure"):
        try:
            _stream.reconfigure(encoding="utf-8", errors="replace")
        except (ValueError, OSError):
            pass

from event_sim.mechanism import compare_candidates, load_queue_series  # noqa: E402

REPORTS_DIR = _PROJECT_ROOT / "docs" / "replays"
DEFAULT_SERIES = "socal_queue_2021"


def render_console(result: dict) -> str:
    out: list[str] = []
    rule = lambda t: f"\n{t}\n{'-' * len(t)}"  # noqa: E731

    out.append(f"H1 MECHANISM TEST — {result['title']}")
    out.append(f"series={result['series']}  n={result['n_observations']}  (no simulation involved)")

    out.append(rule("CANDIDATE FORMS"))
    for name, formula in result["candidates"].items():
        out.append(f"  {name:<12} {formula}")

    shape = result["shape"]
    out.append(rule("SHAPE DIAGNOSTIC (no fitting, no parameters)"))
    out.append(f"  observed    : {[int(v) for v in shape['values']]}")
    out.append(f"  increments  : {[int(v) for v in shape['increments']]}")
    out.append(f"  decaying?   : {shape['increments_decaying']}")
    out.append(f"  -> {shape['verdict']}")
    out.append(f"  {shape['reasoning']}")

    out.append(rule("FIT COMPARISON"))
    relax, stock = result["relaxation_fit"], result["stock_fit"]
    out.append(f"  relaxation (2 params: r, P)   r={relax['r']:.2f} P={relax['driver_constant']:.0f}")
    out.append(f"    predicted : {[round(v, 1) for v in relax['predicted']]}")
    out.append(f"    SSE={relax['sse']:.1f}  RMSE={relax['rmse']:.2f}")
    out.append(f"  stock      (1 param: k)       k={stock['net_imbalance_per_period']:.1f} per period")
    out.append(f"    predicted : {[round(v, 1) for v in stock['predicted']]}")
    out.append(f"    SSE={stock['sse']:.1f}  RMSE={stock['rmse']:.2f}")
    ratio = result["sse_ratio_relaxation_over_stock"]
    if ratio:
        out.append(f"  relaxation SSE is {ratio:.2f}x the stock SSE, with one MORE free parameter")

    out.append(rule("IMPLIED DRIVER (the decisive check — needs no fit)"))
    for label, implied in result["implied_driver"].items():
        out.append(f"  {label}: {implied['claim']}")
    ctx = result["driver_context"]
    if ctx:
        out.append(f"  Actual driver: {ctx.get('claim', '')}")
        figures = ctx.get("figures_attributed_to_port_of_los_angeles_releases", {})
        if figures:
            out.append("    " + "  ".join(f"{k}={v:,}" for k, v in sorted(figures.items())))
        out.append(f"    provenance: {ctx.get('provenance_tier', '')}")

    out.append(rule("VERDICT"))
    out.append(f"  {result['verdict']}")
    out.append(f"  {result['reason']}")

    out.append(rule("LIMITATIONS"))
    for item in result["limitations"]:
        out.append(f"  - {item}")
    out.append(rule("EXCLUDED OBSERVATIONS (definitional inconsistency)"))
    for item in result["excluded_observations"]:
        out.append(f"  - {item['value']} on {item.get('date', '?')}: {item['reason']}")

    out.append("")
    out.append(result["framing"])
    return "\n".join(out)


